-- =============================================================================
-- 20261001090100_event_venue.sql
--
-- 给活动加"地点"字段。
--
-- -----------------------------------------------------------------------------
-- 为什么需要
--
-- UI/UX 规范 §8.1/§8.2 要求活动卡片与 hero 上显示 "venue/online label"
-- （场地 / 线上）。但 `events` 表从 Phase 1 起只有 `meeting_url`（会议链接），
-- **没有场地列** —— 于是"这周在哪打"这件事在系统里无处可写：
-- 线上活动能填链接，线下活动只能写在"活动说明"那段自由文字里，
-- 学生看不出结构化的地点。
--
-- 2026-10-01 产品负责人决定：加这一列。
--
-- -----------------------------------------------------------------------------
-- 为什么可以留空
--
-- 线上活动没有场地，线下活动没有链接 —— 两者都是"可选"。因此：
--   * 本列可空；
--   * 不改任何现有行（老数据保持 NULL，界面显示为"待定"）；
--   * 不加"场地与链接至少填一个"的约束：规范没有这条要求，
--     而管理员在活动还是草稿时本来就可能两者都还没定。
--     这是一条**产品决定**，不该由我在数据库里替他定死。
-- =============================================================================

alter table public.events add column if not exists venue text;

comment on column public.events.venue is
  '线下场地（例如「教学楼 A101」）。线上活动留空并填写 meeting_url；两者都留空时界面显示「地点待定」。';

-- 长度上限与表单校验保持一致（lib/validation/events.ts 的 venue）。
-- 不加约束的话，一次误粘贴可以把整段文字塞进这个字段。
alter table public.events
  add constraint events_venue_length check (venue is null or char_length(venue) <= 200);
